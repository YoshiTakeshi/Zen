# Consensus constants of the reward curve (SPEC 5.4), generated with mpmath at 50 digits (Justus L. Ludovic).
# Writes ../src/reward_tables.rs (constants for Yen, Ken, Jen and the exp2 table) and ../src/phi_inv_q32.bin
# (65,536 little-endian i64: the inverse standard-normal CDF at (k + 0.5) / 65536 in Q32.32).
# Every node uses these exact integers; the generator is here so anyone can reproduce them.
import struct, hashlib, sys
from mpmath import mp, mpf, log, sqrt, erfinv, power, floor
mp.dps = 50
Q32 = mpf(2) ** 32
Q62 = mpf(2) ** 62
def q32(x): return int(floor(x * Q32 + mpf('0.5')))
out = ["// Generated by tools/gen_reward_tables.py (mpmath, 50 digits). DO NOT EDIT.",
       "// These integers ARE the consensus definition of the reward curve (SPEC 5.4, 5.4.1).", ""]
for name, m in (("YEN", 1), ("KEN", 2), ("JEN", 3)):
    r = (m + sqrt(m * m + 4)) / 2
    log2r = log(r, 2)
    a = 1 / log2r                      # a = ln 2 / ln r
    out += [f"// {name}: metallic ratio r = {mp.nstr(r, 20)}, a = ln2 / ln r = {mp.nstr(a, 20)}",
            f"pub const {name}_LOG2R_Q32: i64 = {q32(log2r)};",
            f"pub const {name}_A_Q32: i64 = {q32(a)};",
            f"pub const {name}_INV_R_Q32: i64 = {q32(1 / r)};", ""]
out.append("/// 2^(2^-(i+1)) in Q2.62, for the bit-by-bit fixed-point exp2")
out.append("pub const EXP2_FRAC_Q62: [u64; 32] = [")
for i in range(1, 33):
    out.append(f"    {int(floor(power(2, mpf(2) ** (-i)) * Q62 + mpf('0.5')))},")
out.append("];")
open("../src/reward_tables.rs", "w").write("\n".join(out) + "\n")
buf = bytearray()
N = 1 << 16
for k in range(N):
    u = (mpf(k) + mpf('0.5')) / N
    z = sqrt(2) * erfinv(2 * u - 1)
    buf += struct.pack("<q", q32(z))
open("../src/phi_inv_q32.bin", "wb").write(bytes(buf))
print("phi_inv_q32.bin sha256", hashlib.sha256(bytes(buf)).hexdigest())
